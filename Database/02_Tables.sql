USE MorningCoffeeDb;
GO
IF OBJECT_ID('dbo.OrderDetails','U') IS NOT NULL DROP TABLE dbo.OrderDetails;
IF OBJECT_ID('dbo.Orders','U') IS NOT NULL DROP TABLE dbo.Orders;
IF OBJECT_ID('dbo.Products','U') IS NOT NULL DROP TABLE dbo.Products;
IF OBJECT_ID('dbo.Categories','U') IS NOT NULL DROP TABLE dbo.Categories;
IF OBJECT_ID('dbo.Customers','U') IS NOT NULL DROP TABLE dbo.Customers;
IF OBJECT_ID('dbo.Users','U') IS NOT NULL DROP TABLE dbo.Users;
GO
CREATE TABLE Users(
 UserId INT IDENTITY(1,1) PRIMARY KEY,
 FullName NVARCHAR(120) NOT NULL, Email NVARCHAR(150) NOT NULL UNIQUE,
 PasswordHash NVARCHAR(100) NOT NULL, Role NVARCHAR(20) NOT NULL DEFAULT 'Customer',
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME()
);
CREATE TABLE Customers(
 CustomerId INT IDENTITY(1,1) PRIMARY KEY,
 FullName NVARCHAR(120) NOT NULL, Email NVARCHAR(150) NOT NULL UNIQUE,
 Phone NVARCHAR(20), Address NVARCHAR(300), CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME()
);
CREATE TABLE Categories(
 CategoryId INT IDENTITY(1,1) PRIMARY KEY,
 Name NVARCHAR(100) NOT NULL UNIQUE, Description NVARCHAR(250), IsActive BIT NOT NULL DEFAULT 1
);
CREATE TABLE Products(
 ProductId INT IDENTITY(1,1) PRIMARY KEY,
 Name NVARCHAR(150) NOT NULL, Description NVARCHAR(500), Price DECIMAL(18,2) NOT NULL,
 CategoryId INT NOT NULL, ImageUrl NVARCHAR(500), IsAvailable BIT NOT NULL DEFAULT 1,
 CreatedAt DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 CONSTRAINT FK_Products_Categories FOREIGN KEY(CategoryId) REFERENCES Categories(CategoryId)
);
CREATE TABLE Orders(
 OrderId INT IDENTITY(1,1) PRIMARY KEY, CustomerId INT NOT NULL,
 Status NVARCHAR(30) NOT NULL DEFAULT 'Pending', PaymentMethod NVARCHAR(30) NOT NULL,
 Subtotal DECIMAL(18,2) NOT NULL, Tax DECIMAL(18,2) NOT NULL, Total DECIMAL(18,2) NOT NULL,
 OrderDate DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 CONSTRAINT FK_Orders_Customers FOREIGN KEY(CustomerId) REFERENCES Customers(CustomerId)
);
CREATE TABLE OrderDetails(
 OrderDetailId INT IDENTITY(1,1) PRIMARY KEY, OrderId INT NOT NULL, ProductId INT NOT NULL,
 ProductName NVARCHAR(150) NOT NULL, UnitPrice DECIMAL(18,2) NOT NULL,
 Quantity INT NOT NULL CHECK(Quantity>0), LineTotal DECIMAL(18,2) NOT NULL,
 CONSTRAINT FK_OrderDetails_Orders FOREIGN KEY(OrderId) REFERENCES Orders(OrderId),
 CONSTRAINT FK_OrderDetails_Products FOREIGN KEY(ProductId) REFERENCES Products(ProductId)
);
GO
CREATE INDEX IX_Products_CategoryId ON Products(CategoryId);
CREATE INDEX IX_Orders_CustomerId ON Orders(CustomerId);
CREATE INDEX IX_OrderDetails_OrderId ON OrderDetails(OrderId);
GO
